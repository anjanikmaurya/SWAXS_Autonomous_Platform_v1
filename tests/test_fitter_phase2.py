# ── the Analyser handles any model ───────────────────────────────────────────

def _load_analyzer(tag="az_phase2"):
    spec = u.spec_from_file_location(tag, str(ROOT / "analyzer" / "app.py"))
    m = u.module_from_spec(spec)
    sys.modules[tag] = m
    spec.loader.exec_module(m)
    return m


def test_analyzer_records_draws_and_reports_a_cylinder(tmp_path, monkeypatch, cylinder):
    az = _load_analyzer()
    monkeypatch.setattr(az, "_project_root", str(tmp_path))
    monkeypatch.setattr(az, "_active_fitter", "catalogue_bic", raising=False)
    calls = []
    monkeypatch.setattr(az, "narrate_fit", lambda d: calls.append(1) or {"summary": "", "flags": []})
    I, s = cylinder
    sub = tmp_path / "1D" / "SAXS" / "Subtracted"
    sub.mkdir(parents=True)
    f = sub / "r001_sample_sub.dat"
    f.write_text("# q_nm-1 I sigma\n" + "\n".join(f"{a:.6g} {b:.6g} {c:.6g}"
                                                  for a, b, c in zip(Q, I, s)) + "\n")
    az._analyze_file(f, drive_loop=False)
    entry = az._results[f.name]
    assert entry["summary"]["model"].split("@")[0] == "cylinder"
    assert entry["plot"]["model"] is not None                          # overlay drawn
    assert np.nanmax(np.asarray(entry["plot"]["model"], float)) > 0
    rec = next((tmp_path / "1D" / "SAXS" / "Results" / "Fit").glob("fit_*.dat")).read_text()
    assert "# Model           : cylinder" in rec and "# Param length" in rec
    assert len(calls) == 1                                             # AI comment once


def test_llm_assisted_comment_is_not_requested_twice(tmp_path, monkeypatch, sphere):
    az = _load_analyzer("az_phase2_llm")
    monkeypatch.setattr(az, "_project_root", str(tmp_path))
    monkeypatch.setattr(az, "_active_fitter", "llm_assisted", raising=False)
    calls = []
    fake = lambda d: calls.append(1) or {"summary": "s", "flags": []}     # noqa: E731
    monkeypatch.setattr(az, "narrate_fit", fake)
    import src.fitting.llm_structure as ls
    monkeypatch.setattr(ls, "_client", lambda: None)          # no AI here: fallback path
    I, s = sphere
    sub = tmp_path / "1D" / "SAXS" / "Subtracted"
    sub.mkdir(parents=True)
    f = sub / "r002_sample_sub.dat"
    f.write_text("# q_nm-1 I sigma\n" + "\n".join(f"{a:.6g} {b:.6g} {c:.6g}"
                                                  for a, b, c in zip(Q, I, s)) + "\n")
    az._analyze_file(f, drive_loop=False)
    # the LLM-assisted fitter supplies its own summary, so the Analyser makes
    # no extra AI call for the comment (it used to make two)
    assert calls == []
    assert az._results[f.name]["full"]["llm"] == az._results[f.name]["full"]["llm_assist"]


def test_broad_spheres_are_fitted_as_spheres_with_the_right_size():
    """The size distribution is integrated over mean ± 6σ (model_fit.PD_NSIGMA).
    With sasmodels' default ±3σ the large-particle tail was cut (scattering ∝ V²),
    the model curve was up to 11 % off at PDI 0.3, and Catalogue + BIC 'explained'
    broad spheres as core-shell or sticky spheres with sizes ~9 % wrong (found by
    tools/analyzer_check.py --loop, Pareto campaign)."""
    from src.simulator.pattern import iq_curve
    from src.fitting.catalogue_bic import select
    from src.analysis.features import compute_features
    from src.analysis import model_fit
    assert model_fit.PD_NSIGMA >= 5
    q = np.geomspace(0.08, 4.0, 250)
    for R, pdi in ((3.0, 0.3), (5.0, 0.25)):
        I = iq_curve(q, R, pdi, scale=1000.0, bkg=0.05)
        s = 0.02 * I + 0.01
        In = np.abs(I + np.random.default_rng(3).normal(0, s))
        sel = select(q, In, s, catalogue=CAT, features=compute_features(q, In, s, with_pr=False))
        w = sel["winner"]
        assert w["model"] == "sphere", (R, pdi, w["model"])
        assert abs(w["equivalent_radius"] - R) / R < 0.02
        assert abs(w["pdi"] - pdi) < 0.03

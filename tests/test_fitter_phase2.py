"""Structure fitter, Phase 2 (docs/design/LLM_FITTER_PLAN.md): the robust model
fitter, the Catalogue + BIC method, and the Analyser handling any model.

Curves are generated by sasmodels itself from known shapes, so the truth is exact.
"""
import importlib.util as u
import sys
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

pytest.importorskip("sasmodels")
pytest.importorskip("scipy")

from src.analysis.features import compute_features  # noqa: E402
from src.analysis.model_fit import fit_model, load_catalogue, seeds_from_features  # noqa: E402

Q = np.geomspace(0.05, 5, 240)          # nm⁻¹
CAT = load_catalogue()


def _curve(name, seed=3, **p):
    from sasmodels.core import load_model
    from sasmodels import data as smd, direct_model as dm
    for k in [k for k in p if k.endswith("_pd")]:    # the full distribution, as real samples
        p.setdefault(k + "_nsigma", 6)                # (sasmodels' default cuts it at ±3σ)
    c = dm.DirectModel(smd.empty_data1D(Q * 0.1), load_model(name))   # sasmodels: Å
    I = np.asarray(c(scale=0.01, background=0.001, **p), float)
    s = 0.02 * I + 2e-4
    return np.abs(I + np.random.default_rng(seed).normal(0, s)), s


@pytest.fixture(scope="module")
def sphere():
    return _curve("sphere", radius=50, radius_pd=0.08, radius_pd_n=35)


@pytest.fixture(scope="module")
def cylinder():
    return _curve("cylinder", radius=20, length=300, radius_pd=0.1, radius_pd_n=25)


def _fit(I, s, model):
    return fit_model(Q, I, s, model, CAT,
                     seeds=seeds_from_features(compute_features(Q, I, s, with_pr=False)))


# ── the robust fitter recovers true parameters ───────────────────────────────

def test_sphere_parameters_are_recovered(sphere):
    r = _fit(*sphere, "sphere")
    assert r["params"]["radius"] == pytest.approx(5.0, rel=0.02)      # nm
    assert r["params"]["radius_pd"] == pytest.approx(0.08, abs=0.02)
    assert r["chi2"] < 1.5 and r["equivalent_radius"] == pytest.approx(5.0, rel=0.02)
    assert r["errors"]["radius"] < 0.2


def test_cylinder_parameters_are_recovered(cylinder):
    r = _fit(*cylinder, "cylinder")
    assert r["params"]["radius"] == pytest.approx(2.0, rel=0.05)
    assert r["params"]["length"] == pytest.approx(30.0, rel=0.1)
    assert r["chi2"] < 1.5


def test_core_shell_contrast_is_found_not_stuck_at_a_bound():
    I, s = _curve("core_shell_sphere", radius=40, thickness=15, sld_core=1, sld_shell=8,
                  sld_solvent=3, radius_pd=0.08, radius_pd_n=25)
    r = _fit(I, s, "core_shell_sphere")
    assert r["chi2"] < 1.5
    assert r["params"]["sld_shell"] == pytest.approx(8.0, abs=0.5)
    assert r["params"]["thickness"] == pytest.approx(1.5, rel=0.1)
    assert "sld_shell" not in r["at_bounds"]


def test_bic_counts_the_two_linear_parameters(sphere):
    r = _fit(*sphere, "sphere")
    assert r["n_free"] == 2 + 2                     # radius, radius_pd + scale, background
    assert r["bic"] == pytest.approx(r["chi2_total"] + 4 * np.log(r["n_points"]), rel=1e-6)


def test_a_bad_model_name_returns_an_error_not_an_exception(sphere):
    assert "error" in fit_model(Q, *sphere, "no_such_model", CAT)


# ── catalogue + BIC picks the right shape ────────────────────────────────────

def test_bic_picks_the_true_shape(sphere, cylinder):
    from src.fitting.catalogue_bic import select
    assert select(Q, *sphere, with_sq=False)["winner"]["model"] == "sphere"
    assert select(Q, *cylinder, with_sq=False)["winner"]["model"] == "cylinder"


def test_catalogue_method_returns_the_fitter_contract(cylinder):
    import src.fitting as F
    r = F.get("catalogue_bic").fit(Q, *cylinder)
    assert r["model"].split("@")[0] == "cylinder"
    assert r["size"]["source"] == "equivalent_rg"
    assert r["size"]["radius"] == pytest.approx(np.sqrt(5 / 3) * r["size"]["shape_rg"], rel=1e-6)
    assert 0.0 <= r["confidence"] <= 1.0 and r["pdi"] is not None
    assert r["fit_curve"]["q"] and len(r["fit_curve"]["q"]) == len(r["fit_curve"]["I"])
    assert [c["model"] for c in r["candidates"]][0] == r["model"]
    assert r["diagnostics"]["method"] == "catalogue_bic"



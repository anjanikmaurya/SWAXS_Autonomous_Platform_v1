"""The app icons shown in README.md / QUICKSTART.md on GitHub.

They are generated by tools/build_doc_icons.py from the app icon set and the
accent colours in swaxs-tokens.css. These tests fail if someone edits an icon
or a colour without re-running it, or links an icon that does not exist.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import build_doc_icons  # noqa: E402


def test_doc_icons_are_current(tmp_path, monkeypatch):
    committed = {p.name: p.read_text(encoding="utf-8")
                 for p in build_doc_icons.OUT.glob("*.svg")}
    monkeypatch.setattr(build_doc_icons, "OUT", tmp_path)
    fresh = {p.name: p.read_text(encoding="utf-8") for p in build_doc_icons.build()}
    assert fresh == committed, "run: python tools/build_doc_icons.py"


def test_doc_icons_are_valid_and_coloured():
    for p in build_doc_icons.OUT.glob("*.svg"):
        ET.fromstring(p.read_text(encoding="utf-8"))  # well-formed XML
        txt = p.read_text(encoding="utf-8")
        assert "prefers-color-scheme: dark" in txt, p.name
        assert re.search(r"svg\{color:#[0-9a-f]{6}\}", txt), p.name


def test_every_app_in_apps_yml_has_a_doc_icon():
    import yaml
    apps = yaml.safe_load((ROOT / "apps.yml").read_text(encoding="utf-8"))["apps"]
    for app in apps:
        if app.get("icon_id"):
            assert app["icon_id"] in build_doc_icons.ICONS, app["id"]


def test_doc_icon_links_resolve():
    for doc in ("README.md", "QUICKSTART.md"):
        text = (ROOT / doc).read_text(encoding="utf-8")
        links = re.findall(r'<img src="([^"]+\.svg)"', text)
        assert len(links) >= 10, doc
        for link in links:
            assert (ROOT / link).is_file(), f"{doc}: {link}"

"""src/fitting/benchmark.py: score fitting methods on curves with a known truth.

Curves are generated by sasmodels from every catalogue shape with randomised,
realistic parameters, Schulz polydispersity, a flat background, a varied
q-range and Gaussian noise. Each fitting method in src/fitting/ is run on each
curve and scored on:

    shape accuracy      did it name the true structure (methods that only fit
                        spheres always answer "sphere")
    size error          |R_eq − R_eq,true| / R_eq,true, with the equivalent radius
                        as reported to the optimiser (√(5/3)·Rg; the radius for a
                        sphere; the primary radius for a mass fractal)
    PDI error           |PDI − PDI_true| where both exist
    calibration         shape accuracy among fits it called confident (≥ 0.5)
    time per curve

Cases are deterministic from (split, index): "practice" and "heldout" never
share a seed, so a method tuned on practice is judged on curves it never saw
(docs/design/LLM_FITTER_PLAN.md). Lengths are nm; sasmodels works in Å.
"""
from __future__ import annotations

import math
import time
from collections import Counter, defaultdict

import numpy as np

SHAPES = ("sphere", "core_shell_sphere", "ellipsoid", "cylinder", "mass_fractal")
SPLIT_OFFSET = {"practice": 0, "heldout": 1_000_003}


def _rng(split: str, i: int):
    return np.random.default_rng(SPLIT_OFFSET[split] + 7919 * i)


def _log_u(r, lo, hi):
    return float(math.exp(r.uniform(math.log(lo), math.log(hi))))


def make_case(split: str, i: int) -> dict:
    """One benchmark case: shape cycles through SHAPES, everything else random."""
    r = _rng(split, i)
    shape = SHAPES[i % len(SHAPES)]
    pd = float(r.uniform(0.03, 0.22))
    if shape == "sphere":
        p = {"radius": _log_u(r, 2, 15)}
        pdp = "radius"
    elif shape == "core_shell_sphere":
        p = {"radius": _log_u(r, 2, 10), "thickness": _log_u(r, 0.6, 4),
             "sld_core": 1.0, "sld_solvent": 3.0,
             "sld_shell": float(r.choice([r.uniform(6, 12), r.uniform(-6, -1)]))}
        pdp = "radius"
    elif shape == "ellipsoid":
        re = _log_u(r, 2, 8)
        aspect = float(r.choice([r.uniform(2.0, 4.0), r.uniform(0.25, 0.5)]))
        p = {"radius_equatorial": re, "radius_polar": re * aspect}
        pdp = "radius_equatorial"
    elif shape == "cylinder":
        R = _log_u(r, 1, 6)
        p = {"radius": R, "length": R * _log_u(r, 6, 25)}
        pdp = "radius"
    else:
        p = {"radius": _log_u(r, 0.5, 3), "fractal_dim_mass": float(r.uniform(1.7, 2.8)),
             "cutoff_length": _log_u(r, 20, 150)}
        pdp, pd = None, None
    return {"id": f"{split}-{i:04d}", "split": split, "index": i, "shape": shape,
            "params": p, "pd_param": pdp, "pdi": pd,
            "q_min": float(r.uniform(0.04, 0.12)), "q_max": float(r.uniform(2.5, 5.0)),
            "n_q": int(r.integers(180, 320)), "noise": float(_log_u(r, 0.008, 0.06)),
            "bkg_frac": float(_log_u(r, 1e-4, 5e-3)), "seed": SPLIT_OFFSET[split] + i}


def _model_call(name, q_nm, params_nm, pd_param=None, pdi=None, pd_n=35):
    from sasmodels.core import load_model
    from sasmodels import data as smd, direct_model as dm
    k = load_model(name)
    info = {pp.name: pp for pp in k.info.parameters.kernel_parameters}
    p = {}
    for n, v in params_nm.items():
        p[n] = v * 10.0 if n in info and (info[n].units or "").strip() == "Ang" else v
    if pd_param and pdi:
        p[f"{pd_param}_pd"] = pdi
        p[f"{pd_param}_pd_n"] = pd_n
        p[f"{pd_param}_pd_type"] = "schulz"
    c = dm.DirectModel(smd.empty_data1D(np.asarray(q_nm) * 0.1), k)
    return np.asarray(c(scale=1.0, background=0.0, **p), float)


def true_equivalent_radius(case: dict) -> float:
    """R_eq as the methods report it, from the noise-free model."""
    p = case["params"]
    if case["shape"] == "sphere":
        return p["radius"]
    if case["shape"] == "mass_fractal":
        return p["radius"]
    lengths = [v for k, v in p.items() if not k.startswith("sld")]
    Rmax = max(lengths)
    qg = np.geomspace(0.02 / Rmax, 0.6 / Rmax, 40)
    I = _model_call(case["shape"], qg, p, case["pd_param"], case["pdi"])
    slope = np.polyfit(qg ** 2, np.log(I), 1)[0]
    return math.sqrt(5.0 / 3.0) * math.sqrt(-3.0 * slope)


def render(case: dict):
    """(q, I, sigma, truth) for a case."""
    r = np.random.default_rng(case["seed"])
    q = np.geomspace(case["q_min"], case["q_max"], case["n_q"])
    I0 = _model_call(case["shape"], q, case["params"], case["pd_param"], case["pdi"])
    I0 = I0 / I0[0]
    I0 = I0 + case["bkg_frac"]
    s = case["noise"] * I0 + 0.2 * case["bkg_frac"]
    I = np.abs(I0 + r.normal(0, s))
    truth = {"shape": case["shape"], "R_eq": true_equivalent_radius(case),
             "pdi": case["pdi"], "params": case["params"]}
    return q, I, s, truth


def run_case(case: dict, methods) -> list[dict]:
    """Run every method on one case. Never raises; failures are rows with ok=False."""
    import src.fitting as F
    rows = []
    try:
        q, I, s, truth = render(case)
    except Exception as exc:                                      # noqa: BLE001
        return [{"case": case["id"], "method": m, "ok": False,
                 "error": f"render: {exc}"} for m in methods]
    for m in methods:
        t0 = time.perf_counter()
        row = {"case": case["id"], "split": case["split"], "method": m,
               "true_shape": truth["shape"], "true_R": truth["R_eq"], "true_pdi": truth["pdi"],
               "noise": case["noise"]}
        try:
            res = F.get(m).fit(q, I, s)
            row.update({"ok": True,
                        "pred_shape": (res.get("model") or "sphere").split("@")[0],
                        "structure_factor": ("@" in (res.get("model") or "")),
                        "pred_R": (res.get("size") or {}).get("radius"),
                        "pred_pdi": res.get("pdi"),
                        "confidence": res.get("confidence")})
        except Exception as exc:                                  # noqa: BLE001
            row.update({"ok": False, "error": f"{type(exc).__name__}: {exc}"})
        row["seconds"] = round(time.perf_counter() - t0, 3)
        rows.append(row)
    return rows


def score(rows: list[dict]) -> dict:
    """Metrics per method (and per split if several are present)."""
    out = {}
    by = defaultdict(list)
    for r in rows:
        by[r["method"]].append(r)
    for m, rs in by.items():
        ok = [r for r in rs if r.get("ok") and r.get("pred_R")]
        n = len(rs)
        shape_hit = [r["pred_shape"] == r["true_shape"] for r in ok]
        size_err = [abs(r["pred_R"] - r["true_R"]) / r["true_R"] for r in ok if r["true_R"]]
        pdi_err = [abs(r["pred_pdi"] - r["true_pdi"]) for r in ok
                   if r.get("pred_pdi") is not None and r.get("true_pdi") is not None]
        conf = [r for r in ok if (r.get("confidence") or 0) >= 0.5]
        per_shape = {}
        for sh in SHAPES:
            s_rows = [r for r in ok if r["true_shape"] == sh]
            if s_rows:
                per_shape[sh] = {
                    "n": len(s_rows),
                    "shape_acc": round(float(np.mean([r["pred_shape"] == sh for r in s_rows])), 3),
                    "size_err_median": round(float(np.median(
                        [abs(r["pred_R"] - r["true_R"]) / r["true_R"] for r in s_rows])), 3),
                }
        confusion = Counter((r["true_shape"], r["pred_shape"]) for r in ok)
        out[m] = {
            "n_cases": n, "n_failed": n - len(ok),
            "shape_acc": round(float(np.mean(shape_hit)), 3) if ok else None,
            "size_err_median": round(float(np.median(size_err)), 3) if size_err else None,
            "size_within_10pct": round(float(np.mean([e <= 0.10 for e in size_err])), 3) if size_err else None,
            "pdi_err_median": round(float(np.median(pdi_err)), 3) if pdi_err else None,
            "confident_frac": round(len(conf) / max(len(ok), 1), 3),
            "shape_acc_when_confident": (round(float(np.mean(
                [r["pred_shape"] == r["true_shape"] for r in conf])), 3) if conf else None),
            "seconds_median": round(float(np.median([r["seconds"] for r in rs])), 2),
            "per_shape": per_shape,
            "confusion": {f"{a}->{b}": c for (a, b), c in sorted(confusion.items())},
        }
    return out


def report_markdown(scores: dict, title: str = "Fitter benchmark") -> str:
    lines = [f"# {title}", "",
             "| Method | Cases | Shape correct | Size error (median) | Size within 10 % "
             "| PDI error (median) | Correct when confident | s / curve |",
             "|---|---|---|---|---|---|---|---|"]
    def pct(v):
        if v is None:
            return "n/a"
        return f"{100 * v:.1f} %" if 100 * v < 10 else f"{100 * v:.0f} %"
    for m, s in scores.items():
        lines.append(f"| `{m}` | {s['n_cases']} | {pct(s['shape_acc'])} | {pct(s['size_err_median'])} "
                     f"| {pct(s['size_within_10pct'])} | {s['pdi_err_median'] if s['pdi_err_median'] is not None else 'n/a'} "
                     f"| {pct(s['shape_acc_when_confident'])} | {s['seconds_median']} |")
    lines += ["", "## Per shape (shape correct / median size error)", "",
              "| Method | " + " | ".join(SHAPES) + " |", "|---|" + "---|" * len(SHAPES)]
    for m, s in scores.items():
        cells = []
        for sh in SHAPES:
            d = s["per_shape"].get(sh)
            cells.append(f"{pct(d['shape_acc'])} / {pct(d['size_err_median'])}" if d else "n/a")
        lines.append(f"| `{m}` | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"
